// 「ゲームの遊び方・記録」（js/gameGuideScreen.js）と「遊び方・機能ガイド」（js/guideScreen.js）が
// 共通で使う、ゲームのモードの説明データ（2026-10-31 新設・本人の依頼 D）。
//
// 【なぜ1つのファイルか】同じゲームの説明を2か所で別々に持つと、片方だけ直して食い違う。
// ゲームの説明はここだけに書き、全体のガイド（js/data/guideContent.js）はここから短い紹介を作る。
//
// 【書き方の決まり】
//   ・秒数・回数・点数・曲数は、コードで確かめた値だけを書く（推測では書かない）。
//     出所：js/score.js（点数・ランク）、js/quiz.js（4曲以上）、js/randomPlaybackEngine.js（5秒）、
//     js/instantChallengeScreen.js（1.5／1／0.5秒・3／5／10問）、js/timeAttackScreen.js（自己ベスト）、
//     js/weakSongStats.js（3回以上・75％未満）、js/onlineBattle.js（1〜10人・6文字のコード）、
//     js/partyBattleState.js（2〜4人）、js/liveCallData.js（コールを覚えるの3つのモードが使える条件）。
//   ・曲数（カテゴリの曲数）は文に書かない。画面（js/gameGuideScreen.js）が js/data/songs.js から数えて差し込む
//     （新曲が増えても古い数が残らないように）。文の中の {count:title-track} などが差し込む場所。
//   ・「こんな人におすすめ」は作り手の提案（事実ではない）。
//
// 1つのモードの形：
//   id         … このガイドの中の名前（全体のガイドの項目 id と同じにしてある：intro / randomPlayback …）
//   title      … 画面の名前（ホームのボタンと同じ名前）
//   icon       … ホームと同じアイコン（index.html の <symbol id="hi-…">）
//   tone       … 色（css/guides.css の .gg-tone--…。ホームのモードの色と同じ）
//   group      … solo（ひとりで挑戦）／together（友達と対戦）／make（つくる・覚える）
//   catch      … 一言の説明（カードに出す）
//   needs      … 遊ぶのに端末に要るデータ（audio：音源／lyrics：歌詞／calls：完成版コール）
//   needsNote  … 要るデータが選び方で変わるときの一言（任意）
//   keyPoints  … 大事な操作（詳しい説明のいちばん上に目立たせて出す。3つ前後）
//   items      … 10の項目（GAME_GUIDE_ITEMS の key。値は文の配列＝1つずつ箇条書き）
//   play       … 「このゲームを遊ぶ」の行き先 { type: "mode", modeId } または { type: "intro" }（ホームのイントロの箱）
//   helpModalId… 前からある「？」の詳しいルール（js/main.js の SPECIAL_MODE_HELP_MODALS など）。無ければ null
//   images     … 説明の画像（今ある画面の見本。ダミーの文字で撮ったもの）。無ければ []

