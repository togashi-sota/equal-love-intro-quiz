// 文の中の {count:カテゴリ} を曲数に置き換える（counts：{ "title-track": 23, ... }）。
// 数が分からないときは「（…曲）」ごと消す（古い数や空の数を出さない）
export function fillGameGuideCounts(text, counts = {}) {
  return String(text)
    .replace(/（\{count:([a-z-]+)\}曲）/g, (whole, key) => (Number.isFinite(counts[key]) ? `（${counts[key]}曲）` : ""))
    .replace(/\{count:([a-z-]+)\}/g, (whole, key) => (Number.isFinite(counts[key]) ? String(counts[key]) : ""));
}
