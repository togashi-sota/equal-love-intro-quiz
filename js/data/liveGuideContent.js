// 開場・開演時刻から、行動の目安を作る（制作者の目安。DOM に触れない純粋関数）
// openTime・startTime は "HH:MM"。戻り値：{ ok, steps: [{ time: "HH:MM", label }], reason }
export function buildArrivalPlan({ openTime, startTime, buyGoods = false, takePhotos = false, bigVenue = false }) {
  const open = parseClock(openTime);
  const start = parseClock(startTime);
  if (open === null || start === null) return { ok: false, steps: [], reason: "開場時刻と開演時刻を入力してください" };
  if (start <= open) return { ok: false, steps: [], reason: "開演時刻は開場時刻より後の時刻にしてください" };
  let arriveOffset = 45 + (bigVenue ? 30 : 0);
  if (takePhotos) arriveOffset += 20;
  const steps = [];
  if (buyGoods) {
    steps.push({ time: null, label: "グッズ：公式の物販案内で販売開始時刻と購入条件を確認し、その時刻に合わせて会場へ（混雑するので開場よりかなり早めの計画に）" });
  }
  steps.push({ time: formatClock(open - arriveOffset), label: `会場付近に到着（開場の${arriveOffset}分前）${takePhotos ? "・写真撮影" : ""}` });
  steps.push({ time: formatClock(open), label: "開場：案内に従って入場（本人確認・手荷物検査）" });
  steps.push({ time: formatClock(start - 30), label: "このころまでに着席：トイレ・飲み物・ペンライトの準備" });
  steps.push({ time: formatClock(start), label: "開演！" });
  return { ok: true, steps, reason: null };
}

function parseClock(text) {
  const match = /^(\d{1,2}):(\d{2})$/.exec(String(text ?? "").trim());
  if (!match) return null;
  const hours = Number(match[1]);
  const minutes = Number(match[2]);
  if (hours > 23 || minutes > 59) return null;
  return hours * 60 + minutes;
}

function formatClock(totalMinutes) {
  const minutes = ((totalMinutes % 1440) + 1440) % 1440;
  return `${String(Math.floor(minutes / 60)).padStart(2, "0")}:${String(minutes % 60).padStart(2, "0")}`;
}
