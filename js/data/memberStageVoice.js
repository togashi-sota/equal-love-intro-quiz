//     確認できたものだけを載せる。Wikipediaやまとめだけが根拠のものは載せない（保留）。
//   ・役名が公式情報で確認できないものは role を null にし、credit に「出演」等を書く。
//   ・単なるライブ・トークイベントは載せない。ナレーションのみは category を「ナレーション」にして区別する。

