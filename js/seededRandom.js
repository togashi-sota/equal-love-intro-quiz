// 「シード（種となる数値）」から、毎回同じ順番の乱数列を作れる関数を提供するファイル。
// 対戦モードで、全端末が同じ乱数列を再現できるようにするために使う
// （Math.random()は端末・タイミングによって結果が変わるため、対戦の公平な再現には使えない）。
//
// アルゴリズムは mulberry32 という、実装が数行で済む軽量な擬似乱数生成器（PRNG）。
// 暗号強度（推測されにくさ）は求めていない。対戦の問題順を全端末で一致させることだけが目的。
//
// 【対戦コードとの関係】将来この関数の中身（アルゴリズム）を変更したくなった場合に、
// 古い対戦コードで作られた問題が再現できなくなるのを防ぐため、対戦コード側に
// 「乱数アルゴリズムのバージョン」を持たせている（js/localBattle.js参照）。
// このファイル自体を変更するときは、そのバージョン番号も必ず上げること。
export const RNG_VERSION = 1;

// シード（0以上の整数）から、呼ぶたびに0以上1未満の乱数を返す関数を作って返す。
// 同じシードから作った関数は、何度実行しても必ず同じ順番の値を返す。
export function createSeededRandom(seed) {
  let state = seed >>> 0; // 32bit符号なし整数に丸める
  return function random() {
    state |= 0;
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// 対戦コードを作るときに使う、0以上0xFFFFFFFF以下のランダムなシード値を1つ生成する。
// （これ自体はMath.random()由来でよい。「対戦を作る人だけが1回だけ使う」ものであり、
// 全端末で再現する必要はないため。）
export function generateRandomSeed() {
  return Math.floor(Math.random() * 0xffffffff);
}
